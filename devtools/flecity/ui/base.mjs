import assert from 'node:assert/strict';
import path from 'node:path';
export {installBaseFixture as prepare} from '../fixtures/base.mjs';
export async function scenario(ctx,page){
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('試験BASE'));
  assert.equal(await page.locator('.overview-stat').count(),4);
  await page.locator('[data-tab="stock"]').click();
  await page.locator('#stockSearch').waitFor();
  await page.locator('[data-stock-filter="low"]').click();
  await page.waitForFunction(()=>document.querySelector('#content').textContent.includes('不足アイテム')&&!document.querySelector('#content').textContent.includes('通常アイテム'));
  await page.locator('[data-tab="memo"]').click();
  await page.locator('#memoSearch').waitFor();
  assert((await page.locator('#content').textContent()).includes('<img src=x'));
  assert.equal(await page.locator('#content img').count(),0);
  assert.equal(await page.evaluate(()=>globalThis.__xss),undefined);
  await page.locator('#memoSearch').fill('日本語');
  await page.waitForFunction(()=>!document.querySelector('#content').textContent.includes('<img src=x'));
  await page.locator('[data-workspace="2"]').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('閲覧用BASE'));
  assert.equal(await page.locator('[data-action="new-note"]').count(),0);
  assert.equal(await page.locator('#memoSearch').inputValue(),'');
  await page.setViewportSize({width:360,height:780});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Horizontal overflow at phone width');
  const label=await page.evaluate(()=>globalThis.__fixtureLabel);
  await page.locator('#newWorkspaceBtn').click();
  await page.locator('#modalForm [name="name"]').fill(label+' BASE');
  await page.locator('#modalForm [name="type"]').selectOption('custom');
  await page.locator('#modalSave').click();
  await page.waitForFunction(label=>document.querySelector('#status').textContent.includes(label),label);
  await page.locator('[data-tab="stock"]').click();
  await page.locator('[data-action="new-stock"]').first().click();
  await page.locator('#modalForm [name="name"]').fill(label+' 在庫');
  await page.locator('#modalForm [name="quantity"]').fill('10');
  await page.locator('#modalSave').click();
  await page.locator('[data-action="stock-adjust"][data-delta="1"]').click();
  await page.waitForFunction(()=>document.querySelector('.stock-count')?.textContent.includes('11'));
  await page.screenshot({path:path.join(ctx.run.dir,'screenshots','base-stock-adjusted.png'),fullPage:true});
  await page.reload();
  await page.locator('[data-workspace]').filter({hasText:label}).click();
  await page.locator('[data-tab="stock"]').click();
  await page.waitForFunction(()=>document.querySelector('.stock-count')?.textContent.includes('11'));
  assert((await page.evaluate(()=>globalThis.__fixtureCalls)).every(r=>['bootstrap','workspaceGet','workspaceOverview','notesList','stockList','workspaceCreate','stockCreate','stockAdjust'].includes(r.action)));
}
